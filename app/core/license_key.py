"""
Signed license codes, verified offline (plans/v5 2026-10-26-signed-license-keys).

A code is "AICTL1.<payload>.<signature>", both segments base64url without
padding. The payload is JSON {plan, email, order, iat, exp}; the signature is
Ed25519 over the payload segment's bytes. Codes are issued by
scripts/internal/issue_license.py with a private key held only by the AIControl team;
installs verify them with PUBLIC_KEY below -- no network call.

license_gate.get_license_info() re-verifies the stored code on every plan
check, so the plan can only come from a code that carries a valid signature.
"""
import base64
import binascii
import json
from dataclasses import dataclass
from datetime import datetime, timezone
from functools import lru_cache
from typing import Optional

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

PREFIX = "AICTL1"
PLANS = ("trial", "business", "enterprise")

# Raw Ed25519 public key, base64url. Not secret: it verifies signatures but
# cannot create them. Generated by `scripts/internal/issue_license.py keygen`.
PUBLIC_KEY = "vwRf2E2ZqZYGAmyBreSDNV2WSTD_-92oa_F5GV6636E"


@dataclass(frozen=True)
class LicensePayload:
    plan: str
    email: str
    order: str
    issued_at: Optional[datetime]
    expires_at: datetime

    def is_expired(self, now: datetime) -> bool:
        return now >= self.expires_at


def _b64encode(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _b64decode(segment: str) -> bytes:
    return base64.urlsafe_b64decode(segment + "=" * (-len(segment) % 4))


def public_key_to_str(public_key: Ed25519PublicKey) -> str:
    return _b64encode(public_key.public_bytes(Encoding.Raw, PublicFormat.Raw))


def encode_license_code(private_key: Ed25519PrivateKey, payload: dict) -> str:
    """Sign payload into a license code. Used by scripts/internal/issue_license.py and tests."""
    payload_segment = _b64encode(json.dumps(payload, separators=(",", ":")).encode())
    signature = private_key.sign(payload_segment.encode())
    return f"{PREFIX}.{payload_segment}.{_b64encode(signature)}"


def _timestamp(value) -> Optional[datetime]:
    if isinstance(value, int) and not isinstance(value, bool):
        try:
            return datetime.fromtimestamp(value, tz=timezone.utc)
        except (OverflowError, OSError, ValueError):
            return None
    return None


@lru_cache(maxsize=64)
def _decode(code: str, public_key: str) -> Optional[LicensePayload]:
    parts = code.split(".")
    if len(parts) != 3 or parts[0] != PREFIX or not public_key:
        return None
    try:
        key = Ed25519PublicKey.from_public_bytes(_b64decode(public_key))
        key.verify(_b64decode(parts[2]), parts[1].encode())
        payload = json.loads(_b64decode(parts[1]))
    except (ValueError, binascii.Error, InvalidSignature):
        return None

    if not isinstance(payload, dict) or payload.get("plan") not in PLANS:
        return None
    expires_at = _timestamp(payload.get("exp"))
    if expires_at is None:
        return None
    return LicensePayload(
        plan=payload["plan"],
        email=str(payload.get("email", "")),
        order=str(payload.get("order", "")),
        issued_at=_timestamp(payload.get("iat")),
        expires_at=expires_at,
    )


def decode_license_code(code: str) -> Optional[LicensePayload]:
    """Return the payload of a correctly signed code with a known plan, or
    None. Expiry is not checked here -- callers compare is_expired(now) on
    every check, since a cached result must not outlive the code."""
    return _decode(code.strip(), PUBLIC_KEY)
